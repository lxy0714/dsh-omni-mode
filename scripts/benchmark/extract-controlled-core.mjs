// Reuse trusted historical evaluator logic without importing its SDK/UI wrapper.
// No model-generated code is read or executed by this generator.
import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
const sha = text => createHash('sha256').update(text).digest('hex');
export function makeControlledCore(source) {
  if (sha(source) !== 'f955b650c74244242e4f2de587e0d0b344bff3d842fc1976f00d64ce43d223da') throw Error('Historical evaluator source drift');
  const declarations = source.slice(source.indexOf('const object='), source.indexOf('\nfunction personaFrom('));
  const execution = source.slice(source.indexOf('function usageAdd('), source.indexOf('\nexport function apply(ctx)'));
  if (!declarations.startsWith('const object=') || !execution.includes('export async function runArm(')) throw Error('Trusted extraction boundaries missing');
  return '// Trusted byte-exact extraction; generated by scripts/benchmark/extract-controlled-core.mjs.\n' +
    "import crypto from 'node:crypto';\n" + declarations + '\n' + execution + '\n';
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.length !== 3 || !['--write', '--check'].includes(process.argv[2])) throw Error('Use --write or --check');
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
  const text = makeControlledCore(fs.readFileSync(path.join(root, 'tools/benchmark-host/index.js'), 'utf8'));
  const output = path.join(root, 'tools/contract-benchmark-host/core.mjs');
  if (process.argv[2] === '--write') fs.writeFileSync(output, text, {flag: 'wx'});
  else if (fs.readFileSync(output, 'utf8') !== text) throw Error('Extracted evaluator differs from its frozen historical implementation');
  console.log(JSON.stringify({trustedCore: 'PASS', bytes: Buffer.byteLength(text), sha256: sha(text), originalChanged: false}));
}
